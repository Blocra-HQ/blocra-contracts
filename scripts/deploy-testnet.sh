#!/usr/bin/env bash
# Deploy the BlocRA report registry to Stellar testnet.
# Writes the contract ID to .env.testnet at the repo root.
#
# Usage: ./scripts/deploy-testnet.sh [--source <identity>] [--admin <G...>] [--fee <stroop>]
#
# Prerequisites:
#   - stellar CLI installed and authenticated (stellar keys list)
#   - STELLAR_ACCOUNT env var set, or pass --source <identity>
#   - Network: testnet (https://soroban-testnet.stellar.org)
#
# The admin (who can pause publishing) defaults to the
# deployer's address and is set by the constructor in the deploy transaction.

set -euo pipefail

# ── Configuration ─────────────────────────────────────────────────────────────

CONTRACTS_DIR="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="${CONTRACTS_DIR}/.env.testnet"
NETWORK="testnet"
RPC_URL="https://soroban-testnet.stellar.org"
NETWORK_PASSPHRASE="Test SDF Network ; September 2015"
FEE="${STELLAR_FEE:-100}"

# ── Parse arguments ────────────────────────────────────────────────────────────

SOURCE="${STELLAR_ACCOUNT:-}"
ADMIN="${REGISTRY_ADMIN:-}"

while [[ $# -gt 0 ]]; do
    case $1 in
        --source) SOURCE="$2"; shift 2 ;;
        --admin)  ADMIN="$2";  shift 2 ;;
        --fee)    FEE="$2";    shift 2 ;;
        *) echo "Unknown argument: $1"; exit 1 ;;
    esac
done

if [[ -z "${SOURCE}" ]]; then
    echo "Error: deployer identity not set."
    echo "  Set STELLAR_ACCOUNT env var or pass --source <identity>"
    exit 1
fi

# ── Helpers ────────────────────────────────────────────────────────────────────

log()  { echo "[$(date -u +%H:%M:%S)] $*" >&2; }
info() { echo "  $*" >&2; }

deploy_contract() {
    local name="$1"   # human-readable label
    local wasm="$2"   # path to .wasm file
    local alias="$3"  # env-file key (e.g. REPORT_REGISTRY_CONTRACT_ID)
    shift 3           # the rest are constructor arguments

    log "Deploying ${name}..."
    if [[ ! -f "${wasm}" ]]; then
        echo "  Error: wasm not found at ${wasm}"
        echo "  Run 'stellar contract build' first."
        exit 1
    fi

    # `|| true` on the pipeline: with `set -e`, a transient deploy failure
    # (grep finding no 56-char ID) would otherwise kill the script right here,
    # silently skipping the error message below — this way the `-z` check
    # gets a chance to report which contract failed before exiting.
    local contract_id
    contract_id=$(stellar contract deploy \
        --wasm "${wasm}" \
        --source "${SOURCE}" \
        --network "${NETWORK}" \
        --fee "${FEE}" \
        -- "$@" \
        2>&1 | grep -E '^[A-Z0-9]{56}$' | tail -1) || true

    if [[ -z "${contract_id}" ]]; then
        echo "  Error: failed to deploy ${name} — no contract ID returned."
        echo "  This can be a transient RPC/network hiccup — try re-running."
        exit 1
    fi

    info "${alias}=${contract_id}"
    echo "${alias}=${contract_id}" >> "${ENV_FILE}"
    echo "${contract_id}"
}

# ── Build ──────────────────────────────────────────────────────────────────────

# soroban-sdk 29 must be built through stellar-cli (v25.2.0+).
log "Building contracts for release..."
(cd "${CONTRACTS_DIR}" && stellar contract build 2>&1 | tail -3)
log "Build complete."

# ── Deploy ─────────────────────────────────────────────────────────────────────

WASM_DIR="${CONTRACTS_DIR}/target/wasm32v1-none/release"

# Start fresh env file
cat > "${ENV_FILE}" <<EOF
# Testnet contract IDs — generated by scripts/deploy-testnet.sh
# Network:    ${NETWORK}
# RPC URL:    ${RPC_URL}
# Passphrase: ${NETWORK_PASSPHRASE}
# Deployer:   ${SOURCE}

EOF

log "Starting deployment to ${NETWORK}..."
echo ""

if [[ -z "${ADMIN}" ]]; then
    ADMIN=$(stellar keys address "${SOURCE}")
fi
info "Admin: ${ADMIN}"

REGISTRY_ID=$(deploy_contract \
    "report_registry" \
    "${WASM_DIR}/report_registry.wasm" \
    "REPORT_REGISTRY_CONTRACT_ID" \
    --admin "${ADMIN}")

# ── Summary ────────────────────────────────────────────────────────────────────

echo ""
log "Contract deployed successfully."
log "Contract IDs written to: ${ENV_FILE}"
echo ""
echo "  REPORT_REGISTRY_CONTRACT_ID=${REGISTRY_ID}"
echo ""
log "Set VITE_REPORT_REGISTRY_CONTRACT_ID=${REGISTRY_ID} in the blocra-frontend environment."
